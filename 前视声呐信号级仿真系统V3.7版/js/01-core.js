/* =================================================================
 * ★ V3.2：参数联动（derived quantities）
 * -----------------------------------------------------------------
 * 由来：V3.1 及以前，下面这些量是各自独立的输入框 ——
 *     · 「阵元垂直指向性开角」手填 60°，而阵元垂直长度根本不存在的量；
 *     · 「波束数」手填 181，与 64 元 λ/2 阵（θ₃dB≈1.6°）、120° 扇角毫无关系。
 *   于是很容易出现自相矛盾的组合：改了阵元数、波束数仍停在 181，
 *   实际波束角变成 0.66° 或 1.9°（一个过采样、一个漏检），而界面上毫无提示。
 *
 * 现在把这些**算得出来的量一律算出来**，只保留真正独立的物理输入：
 *
 *   波长        λ   = c / f₀
 *   接收孔径    D   = M·d                       （M 元、间距 d 的均匀线阵）
 *   阵列波束    θ₃ = 0.886 λ / D           [rad]（均匀加权、法向）
 *   波束角      Δθ  = k · θ₃                    （k = alg.beamK，0.5~0.7）
 *   波束数      N   = 2^⌈log₂(扇角/Δθ)⌉         （向上取 2 的幂，夹在 16~512）
 *   阵元垂直开角 θ_v = 2·arcsin(0.443 λ / L_v)  （L_v = rx.elemVLen）
 *
 * 为什么 θ₃ 用**法向**值而不是扇区边缘值：斜视 θ 处波束会展宽到 θ₃/cosθ，
 * 边缘最宽。采样定理要求每个波束宽度内至少两个波束，约束最紧的是**最窄**处
 * 也就是法向 —— 按法向取值，边缘自然过采样（安全侧），反之边缘会漏检。
 *
 * 每次参数改动后调用一次 FLS.derive()（见 99-app.js onParamChange 首行）。
 * 它**只写这两个派生量**，不触发任何重算/重绘，也不会递归回调。
 * ================================================================= */
/* =================================================================
 * ★ V3.6：−3dB 波束宽度的**精确**求法（而不是背公式）
 * -----------------------------------------------------------------
 * 教科书公式 θ₃ = 0.886λ/D 只对**均匀加权（矩形窗）**成立。一旦开了
 * 旁瓣抑制（默认就是汉宁窗），主瓣会展宽约 1.4~1.5 倍 —— 也就是说
 * 「阵元数、间距、波长、加权窗」四者共同决定真实波束宽度，缺一不可。
 * 旧版只用 0.886λ/D，于是：
 *   ① 界面上写的 θ₃ 比实际波束窄 44%（默认汉宁窗）；
 *   ② 由它推出的波束角 Δθ = k·θ₃ 和波束数 N 也一起偏窄/偏多 ——
 *      改「加权窗」对波束数毫无影响，正是典型的没联动。
 *
 * 这里直接对**真实的阵列因子**做数值求根，用的就是内核那套阵元位置
 * 与内核那个窗函数（FLS.Win），因此结果与图像里看到的波束完全一致：
 *     A(u) = | Σ_m w_m · e^{−j·(2π/λ)·s_m·u} | ,  u = sinθ
 *     s_m = (m − (M−1)/2)·d
 *   求 A(u₃) = A(0)/√2 的最小正根 → θ₃ = 2·arcsin(u₃)
 * 在 u 域求根而不是 θ 域：A 只依赖 sinθ，u∈[0,1] 是有界区间，
 * 不必担心大孔径时 −3dB 点跑出 ±90°（那时直接判"≥180°"）。
 * 开销：粗扫 512 点 + 二分 30 次，每次 O(M)，M=512 时约 0.3 ms，可忽略。
 */
FLS.beam3dB = function (M, d, lam, winType, sllOn) {
  M = Math.max(2, M | 0);
  d = Math.max(1e-9, d);
  lam = Math.max(1e-9, lam);
  var w = null;
  if (sllOn && FLS.Win) { try { w = FLS.Win(winType || 'rect', M, 30); } catch (e) { w = null; } }
  var s = new Float64Array(M), m;
  for (m = 0; m < M; m++) s[m] = (m - (M - 1) / 2) * d;
  var k = 2 * Math.PI / lam;
  function A(u) {
    var sr = 0, si = 0;
    for (var j = 0; j < M; j++) {
      var ph = -k * s[j] * u, ww = w ? w[j] : 1;
      sr += ww * Math.cos(ph); si += ww * Math.sin(ph);
    }
    return Math.sqrt(sr * sr + si * si);
  }
  var A0 = A(0), tgt = A0 * Math.SQRT1_2;      // −3dB 电平
  if (!(A0 > 0)) return 180;
  /* 粗扫：找第一个跌破 −3dB 的格子 */
  var NS = 512, prev = A0, u3 = -1, i;
  for (i = 1; i <= NS; i++) {
    var u = i / NS, av = A(u);
    if (av <= tgt) { u3 = u; break; }
    prev = av;
  }
  if (u3 < 0) return 180;                      // ±90° 内都没跌到 −3dB → 全向
  /* 二分细化（区间 [u−1/NS, u]） */
  var lo = (i - 1) / NS, hi = u3;
  for (var it = 0; it < 30; it++) {
    var mid = 0.5 * (lo + hi);
    if (A(mid) <= tgt) hi = mid; else lo = mid;
  }
  var uu = 0.5 * (lo + hi);
  if (uu > 1) uu = 1;
  return 2 * Math.asin(uu) / FLS.U.DEG;
};

FLS.dv = {};
FLS.derive = function () {
  var DEG = FLS.U.DEG;          // ← 本函数在顶层作用域，取不到 01-core 私有 IIFE 里的 DEG
  var P = FLS.P;
  var c = (FLS.Env && FLS.Env.profileAt && FLS.state)
    ? FLS.Env.profileAt(FLS.state.rov.z) : 1500;
  if (!isFinite(c) || c < 1000) c = 1500;
  var fcHz = (parseFloat(P['tx.fc']) || 400) * 1000;
  var lam = c / fcHz;                                   // m
  var M = Math.max(2, P['rx.nElem'] | 0);
  var dmm = parseFloat(P['rx.spacing']) || (lam * 500);
  var d = dmm / 1000;                                   // m
  var D = Math.max(1e-4, M * d);                        // 孔径（M·d）
  /* ★ V3.6：θ₃ 不再背 0.886λ/D，而是对**含加权窗的真实阵列因子**数值求根。
     0.886λ/D 只对均匀加权成立；默认开着汉宁窗，真实主瓣要宽 44%，
     界面上的 θ₃、由它推出的波束角 Δθ 与波束数 N 全都偏窄/偏多。
     th3Rect 保留为"均匀加权基准"，只用于在提示里给出展宽系数。 */
  var th3Rect = 0.886 * lam / D / DEG;                  // 度（均匀加权基准）
  var th3 = FLS.beam3dB(M, d, lam, P['alg.shade'], !!P['alg.sll']);   // 度（真实 −3dB 全宽）
  var winFac = th3 / Math.max(1e-9, th3Rect);           // 加权窗带来的主瓣展宽倍数
  /* 扇区边缘的波束宽度：斜视 θ 处波束按 1/cosθ 展宽，扇区边缘最宽。
     扇角接近 180° 时 cos→0，展宽趋于无穷，这里直接判 180°（全向）。 */
  var cEdge = Math.cos(0.5 * (Math.max(20, Math.min(360, parseFloat(P['alg.sector']) || 120))) * DEG);
  var th3Edge = (cEdge > 1e-3) ? Math.min(180, th3 / cEdge) : 180;
  /* ★ V3.6：栅瓣起始角 —— 由「阵元间距 / 波长」直接决定。
     波束扫到 θ₀ 时，栅瓣落在 sinθ_g = sinθ₀ − λ/d；它进入可见区（|sinθ|≤1）
     的条件是 |sinθ₀| ≥ λ/d − 1，于是
         θ_g = arcsin(λ/d − 1)
     就是"扫描角超过 ±θ_g 之后出现栅瓣"的临界角。
       d = λ/2 → θ_g = 90°  （全扫描范围无栅瓣，即半波长准则）
       d = 0.75λ → θ_g = 19.5°（扫过 19.5° 就出栅瓣）
       d ≥ λ    → θ_g ≤ 0°  （法向就有栅瓣） */
  var lamOverD = lam / Math.max(1e-9, d);
  var gArg = Math.max(-1, Math.min(1, lamOverD - 1));
  var thGrat = Math.asin(gArg) / DEG;                   // 度
  var k = Math.max(0.3, Math.min(1.0, parseFloat(P['alg.beamK']) || 0.7));
  var dth = k * th3;
  var sector = Math.max(20, Math.min(360, parseFloat(P['alg.sector']) || 120));
  var nRaw = sector / dth;
  var n = Math.pow(2, Math.ceil(Math.log(Math.max(1.0001, nRaw)) / Math.LN2));
  if (!isFinite(n) || n < 16) n = 16;
  if (n > 512) n = 512;
  var dthAct = sector / n;                              // 实际波束角
  var kAct = dthAct / th3;                              // 实际系数（≤ k）

  /* —— 阵元垂直开角：由阵元长度算出 —— */
  var Lv = Math.max(0.1, parseFloat(P['rx.elemVLen']) || 3.2) / 1000;   // m
  var sv = 0.443 * lam / Lv;
  var vOpen = (sv >= 1) ? 180 : 2 * Math.asin(sv) / DEG;

  /* —— 发射换能器：垂直叠阵 → 垂直开角 ——
   * ★ V3.3：tx.vbeam 从"手填输入"改成"由 tx.nElem（垂直叠层数）算出"。
   *
   * 物理：前视声呐的发射阵是"竖着摞起来的一叠"（扇形投影器）。N_t 层、层间距
   * 固定取 λ/2，则垂直方向 −3dB 全宽（均匀激励、法向）
   *       θ_v = 2·arcsin(0.886 / N_t)
   * 与频率无关（因为间距随 λ 缩放），只由层数决定。
   *
   * 旧版把 tx.vbeam 做成独立输入框、把 tx.nElem（当时的"发射阵元数"）做成
   * 另一个独立输入框，两者谁都不影响谁 —— 改层数图像一动不动，是典型的空改。
   * 更糟的是它们可以互相矛盾（8 层说成 20°，实际该是 12.7°），
   * 界面还照着手填值去算照射范围。现在只有一个物理输入：层数。 */
  var Mt = Math.max(2, P['tx.nElem'] | 0);
  var sv0 = 0.886 / Mt;
  var vTx = (sv0 >= 1) ? 180 : 2 * Math.asin(sv0) / DEG;   // 度
  if (!isFinite(vTx)) vTx = 20;

  /* —— 尺度类派生量 —— */
  var B = (parseFloat(P['tx.bw']) || 40) * 1000;                 // 带宽 Hz
  var fs = (parseFloat(P['rx.fs']) || 400) * 1000;               // 标称采样率 Hz
  var Kdec = Math.max(1, Math.floor(fs / (2.5 * B)));            // 整数抽取因子
  var fsbb = fs / Kdec;                                          // 基带采样率 Hz
  var Tp = (parseFloat(P['tx.pulse']) || 5) / 1000;              // 脉宽 s
  var prp = (parseFloat(P['tx.prp']) || 100) / 1000;             // PRP s
  var rUn = c * prp / 2;                                         // 不模糊距离 m
  var dR = c / (2 * B);                                          // 距离分辨率 m
  var nBin = Math.max(8, P['alg.nBin'] | 0);
  var BT = B * Tp;                                               // 时间带宽积
  var gainPC = 10 * Math.log10(Math.max(1, BT));                 // 脉压增益 dB

  /* —— ★ V3.4：带通截止频率与信号频率的联动 ——
   * 射频带通 [fLo, fHi] 的物理含义是"只允许这一段射频通过"。
   * 信号占据 fc ± B/2，因此**正确**的自动值就是
   *      fLo = fc − B/2，fHi = fc + B/2      （默认 400 ± 20 → 380 / 420 kHz）
   * 旧默认 180 / 220 kHz 是 200 kHz 频段，与本机的 400 kHz 信号毫无关系；
   * 它之所以没暴露，是因为旧代码只取 |fHi − fLo| 当带宽（40 kHz），
   * 与自动模式 bw/2 = 20 kHz 数值巧合相等 —— 一个数值巧合掩盖了一个语义错误。
   * 现在自动模式下这两个框由下式写出，改 fc 或 bw 都立刻跟着走；
   * 手动模式下用户可以任意挪动通带（包括故意挪到信号之外去做抗干扰试验），
   * 内核会按"基带映射"真正滤掉带外，不再是无条件的低通。 */
  var fcK = (parseFloat(P['tx.fc']) || 400), bwK = (parseFloat(P['tx.bw']) || 40);
  var bpLo = fcK - bwK / 2, bpHi = fcK + bwK / 2;
  if (P['rx.bpAuto']) { P['rx.bpLo'] = Math.round(bpLo * 10) / 10; P['rx.bpHi'] = Math.round(bpHi * 10) / 10; }
  else { bpLo = parseFloat(P['rx.bpLo']); bpHi = parseFloat(P['rx.bpHi']);
         if (!isFinite(bpLo)) bpLo = fcK - bwK / 2; if (!isFinite(bpHi)) bpHi = fcK + bwK / 2; }
  var bpW = Math.abs(bpHi - bpLo);          // 通带宽度 kHz
  var bpMid = 0.5 * (bpLo + bpHi);          // 通带中心 kHz（射频）

  /* —— 几何派生：近场盲区、俯仰余量 —— */
  var baseDepth = (FLS.P && parseFloat(P['terr.base'])) ? parseFloat(P['terr.base']) : 200;
  var rovZ = (FLS.state && FLS.state.rov) ? FLS.state.rov.z : -196;
  var alt = Math.max(0.5, rovZ + baseDepth);                     // 离底高度 m
  /* ★ V3.6 修复：这里原来是 0.5·vTx / DEG —— DEG = π/180 是"每度的弧度数"，
     度→弧度要**乘**，除以它是把 10.2° 变成 584 rad。tan 的周期性让它碰巧
     落在 0.064 rad 上（584.4 − 93×2π），于是"近场盲区"算出 156 m，
     而正确值（界面注释里就写着）是 10/tan(10.2°) = 55.6 m —— 差 2.8 倍。
     参数面板「近场盲区」那一行显示的就是这个错值。 */
  var vHalf = 0.5 * vTx * DEG;                                   // 半开角（rad）
  var blind = (Math.tan(vHalf) > 1e-6) ? alt / Math.tan(vHalf) : 0;  // 近场盲区 m
  var rmaxNow = parseFloat(P['alg.rmax']) || 60;
  /* —— ★ V3.4：海底平面尺寸（长 × 宽）——
   * 这两个是真正独立的场景自由度，只做钳位、不做推导。
   * 它们同时喂给两处：散射栅格（30-scatter bakeGeom）与三维海床（60-scene3d）。 */
  var lenX = Math.max(20, Math.min(4000, parseFloat(P['terr.lenX']) || 300));
  var lenY = Math.max(20, Math.min(4000, parseFloat(P['terr.lenY']) || 300));
  P['terr.lenX'] = Math.round(lenX); P['terr.lenY'] = Math.round(lenY);
  /* 俯仰的"有用上限"就是垂直半开角 θ_v/2：扇面中心线从水平转到这个角度，
     正好扫过量程远端的掠射角，再往下转远端就开始熄灭。
     实测（V3.3 工况：200 m 平坦海底、离底 4 m、量程 60 m、5 层 20.4°）：
       俯仰 0/3/6/10/20° → 15 m 处 40.6/55.5/69.5/84.6/91.5 M，
                          57 m 处 30.6/32.1/32.2/30.3/18.1 M。
     即"近端越来越亮、远端基本不动"，超过 θ_v/2 之后远端才真的掉下去。 */
  var tiltMax = 0.5 * vTx;

  /* 写回派生量（在 P 里的只有这些：开角 / 波束数 / 阵列尺度 / 采样派生） */
  P['rx.vOpen'] = Math.round(vOpen * 10) / 10;
  P['tx.vbeam'] = Math.round(vTx * 10) / 10;
  P['alg.nBeam'] = n;
  /* ★ V3.6：接收基阵的四个尺度派生量，全部摆在「接收基阵」那一栏 */
  P['rx.aperture'] = Math.round(D * 1000 * 10) / 10;                  // mm
  P['rx.beam3'] = Math.round(th3 * 100) / 100;                        // °
  P['rx.beam3Edge'] = Math.round(th3Edge * 100) / 100;                // °
  /* 栅瓣：θ_g ≥ 89.9° 记为"无"（半波长准则满足，全扫描范围无栅瓣） */
  P['rx.grating'] = (thGrat >= 89.9) ? 0 : Math.round(thGrat * 10) / 10;   // 0 = 无
  P['rx.fsbb'] = Math.round(fsbb / 100) / 10;          // kHz，一位小数
  P['rx.decim'] = Kdec;
  P['alg.rUnamb'] = Math.round(rUn * 10) / 10;

  /* ★ V3.6：自适应算法实际参与的阵元数。
     useM = min(M, adapM)：自适应类（MVDR/LCMV/ACW）要对每个 (距离门 × 波束)
     解一次 useM 阶方程组，代价 ∝ useM²，全阵参与在大阵列上不可承受，
     所以内核里一直有个封顶。问题是它**从来没在界面上出现过** ——
     用户把阵元数从 64 加到 512，CBF 的波束变窄了，MVDR 的却纹丝不动，
     这就是典型的"改了没反应"。现在把它显式化并给出告警。 */
  var adapM = Math.max(0, P['alg.adapM'] | 0);        // 0 = 不封顶（全阵）
  var useMAdap = adapM > 0 ? Math.min(M, adapM) : M;
  var methodNow = P['alg.method'] || 'cbf';
  var isAdap = (methodNow === 'mvdr' || methodNow === 'lcmv' || methodNow === 'acw');
  var isEig = (methodNow === 'esb' || methodNow === 'music');
  var Lsub = Math.min(M, Math.max(2, P['alg.subLen'] | 0));
  var nsrcEff = Math.max(1, Math.min(Lsub - 1, P['alg.nsrc'] | 0));

  var dv = FLS.dv = {
    c: c, lam: lam, lamMm: lam * 1000,
    M: M, d: d, dmm: dmm, D: D, Dmm: D * 1000,
    th3: th3, th3Rect: th3Rect, winFac: winFac, th3Edge: th3Edge,
    thGrat: thGrat, lamOverD: lamOverD,
    k: k, dth: dth, sector: sector, nRaw: nRaw, n: n,
    dthAct: dthAct, kAct: kAct,
    adapM: adapM, useMAdap: useMAdap, isAdap: isAdap, isEig: isEig,
    Lsub: Lsub, nsrcEff: nsrcEff,
    Lv: Lv * 1000, vOpen: P['rx.vOpen'],
    Mt: Mt, vTx: P['tx.vbeam'], hbeam: parseFloat(P['tx.hbeam']) || 120,
    vbeam: P['tx.vbeam'],
    alt: alt, blind: blind, tiltMax: tiltMax, tilt: parseFloat(P['alg.tilt']) || 0,
    B: B, fs: fs, fsbb: fsbb, Kdec: Kdec, Tp: Tp, BT: BT, gainPC: gainPC,
    rUn: rUn, dR: dR, nBin: nBin, sampPerBin: 0, rmax: rmaxNow,
    lenX: P['terr.lenX'], lenY: P['terr.lenY'],
    bpLo: bpLo, bpHi: bpHi, bpW: bpW, bpMid: bpMid, bpOff: bpMid - fcK
  };

  /* —— 一致性检查：只收集，不打印（界面在参数页底部统一列出） —— */
  var W = [];
  if (sector > (parseFloat(P['tx.hbeam']) || 120) + 0.01)
    W.push('成像扇角 ' + sector + '° 大于发射水平开角 ' + P['tx.hbeam'] + '°：扇面两翼没有照射，只剩噪声。');
  if (P['rx.vOpen'] + 0.5 < vTx)
    W.push('阵元垂直开角 ' + P['rx.vOpen'] + '° 小于发射垂直开角 ' + vTx +
      '°：发射照到的那部分海底收不到（能量白打）。要收全就把阵元垂直长度改短，或把垂直叠层数减少。');
  if (dmm > dv.lamMm / 2 + 1e-6)
    W.push('接收阵元间距 ' + dmm.toFixed(2) + ' mm > λ/2 (' + (dv.lamMm / 2).toFixed(2) + ' mm)：出现栅瓣。');
  if ((P['alg.subLen'] | 0) > M - 1)
    W.push('子阵长度 ' + P['alg.subLen'] + ' 应 ≤ 阵元数−1 (' + (M - 1) + ')。');

  /* ★ V3.6 新增四条"改了不起作用"的告警 —— 全部来自本次波束形成算法校核 ------ */
  /* ① 自适应算法的实际参与阵元数被封顶：加阵元数对 MVDR/LCMV/ACW 无效 */
  if (isAdap && adapM > 0 && useMAdap < M)
    W.push('当前算法（' + methodNow.toUpperCase() + '）实际只用前 ' + useMAdap +
      ' 个阵元（受「自适应参与阵元上限」' + adapM + ' 限制），阵元数 ' + M +
      ' 中的后 ' + (M - useMAdap) + ' 个不参与。等效孔径只有 ' +
      (useMAdap * dmm).toFixed(1) + ' mm（全阵 ' + (M * dmm).toFixed(1) +
      ' mm），方位分辨率按 ' + useMAdap + ' 元算。想让加阵元数真正生效，' +
      '把「自适应参与阵元上限」提到 ' + M + '（代价是帧耗时按平方上升）。');
  /* ② 波束数被 16/512 钳住 → 实际波束角大于设计值 → 方位可能漏检 */
  if (kAct > k + 0.02)
    W.push('波束数被钳在 ' + n + '（下限 16 / 上限 512），实际波束角 ' +
      dthAct.toFixed(3) + '° = ' + kAct.toFixed(2) + '×θ₃，大于设计值 ' +
      k.toFixed(2) + '×θ₃：方位采样不足，点目标可能落在两波束之间被切掉一半（掉 3 dB 以上）。' +
      (n >= 512 ? '减小扇角、或把波束角系数 k 调大。' : '减小扇角或增大阵元数。'));
  /* ③ 信源数被子阵长度钳住 */
  if ((P['alg.nsrc'] | 0) > nsrcEff)
    W.push('信源数被钳到 ' + nsrcEff + '（须 ≤ 子阵长度−1 = ' + (Lsub - 1) +
      '）：ESB 的投影子空间与 MUSIC 的噪声子空间划分按 ' + nsrcEff + ' 算。' +
      '要按 ' + P['alg.nsrc'] + ' 个信源分解，把「子阵长度」提到 ' + ((P['alg.nsrc'] | 0) + 1) + ' 以上。');
  /* ④ 大阵列的耗时提示（阵元数上限已放宽到 512，这条是护栏） */
  if (M > 128)
    W.push('接收阵元数 ' + M + ' > 128：回波合成与波束形成的开销都正比于阵元数，' +
      '单帧耗时大约按 M/128 线性上升（128 元实测约 4 s/帧，' + M + ' 元约 ' +
      (4 * M / 128).toFixed(0) + ' s/帧）。做参数扫描建议先用 64~128 元定好方案，再拉到 ' +
      M + ' 元出图。' + (isAdap ? '当前还叠加了自适应求解（∝ 阵元数²），会更慢。' : ''));
  /* ★ V3.3：每单元采样点按**基带**采样率算。旧版误用标称 fs，
     结果虚高 K 倍（默认虚高 4 倍），"欠采样"告警要到 nBin>1000 才可能出现。 */
  var sampPerBin = (rmaxNow - (parseFloat(P['alg.rmin']) || 0)) / nBin * 2 / c * fsbb;
  dv.sampPerBin = sampPerBin;
  if (sampPerBin < 1.0)
    W.push('距离单元 ' + nBin + ' 个只对应 ' + sampPerBin.toFixed(2) + ' 个采样点/单元：欠采样，径向会出现假细节。减少距离单元数或提高采样率。');

  /* ★ V3.3 新增：三类"参数被静默截断/失效"的显式告警 ----------------------
   * 这三条以前都是"改了不起作用还不告诉你"，是用户所说的"空改"里最气人的一种：
   *   ① 量程超过不模糊距离 → 内核里 Math.min(rmax, rUnamb·0.98) 静默截断；
   *   ② 采样率低于 2.5B     → 抽取因子被钳到 1，基带真的欠采样，图像出现混叠；
   *   ③ 成像俯仰过大        → 扇面被压到海底以下，远端只剩噪声（物理上必然）。 */
  if (rmaxNow > rUn * 0.98 + 1e-6)
    W.push('最大探测距离 ' + rmaxNow.toFixed(0) + ' m 超过不模糊距离 ' + rUn.toFixed(0) +
      ' m（c·PRP/2）：超出部分会距离折叠，实际成像距离被截到 ' + (rUn * 0.98).toFixed(0) +
      ' m。要看得更远，把 PRP 提到 ' + (2 * rmaxNow / c * 1000).toFixed(0) + ' ms 以上。');
  if (fs < 2.5 * B - 1)
    W.push('采样率 ' + (fs / 1000).toFixed(0) + ' kHz 低于 2.5 倍带宽 (' + (2.5 * B / 1000).toFixed(0) +
      ' kHz)：抽取因子被钳到 1，基带欠采样，图像沿径向出现混叠。把采样率提到 ' +
      (2.5 * B / 1000).toFixed(0) + ' kHz 以上。');
  /* ★ V3.4：带通通带与信号频带对不上 —— 以前这类设置是"改了完全没反应"，
   * 因为内核无条件按 bw/2 做低通，通带中心在哪儿根本不起作用。现在真按
   * 基带映射滤波，通带挪开就会真的把信号滤掉，所以必须提前告诉用户。 */
  if (FLS.P['rx.bpOn'] && !FLS.P['rx.bpAuto']) {
    var devOff = Math.abs(bpMid - fcK);                 // 通带中心偏离 fc 多少 kHz
    if (devOff > bwK / 2 + 0.01)
      W.push('带通中心 ' + bpMid.toFixed(1) + ' kHz 偏离中心频率 ' + fcK +
        ' kHz 达 ' + devOff.toFixed(1) + ' kHz（信号只占 ±' + (bwK / 2).toFixed(1) +
        ' kHz）：通带已移到信号频带之外，回波会被真的滤掉（图像整体变暗甚至全黑）。' +
        '想做抗干扰试验这是对的，否则请把通带设回 ' + (fcK - bwK / 2) + '~' + (fcK + bwK / 2) + ' kHz。');
    else if (bpW < bwK - 0.01)
      W.push('带通宽度 ' + bpW.toFixed(1) + ' kHz 小于信号带宽 ' + bwK.toFixed(1) +
        ' kHz：通带边缘把信号频谱切掉了，距离分辨率会退化到 c/(2·' + bpW.toFixed(1) +
        ' kHz) = ' + (1500 / (2 * bpW * 1000)).toFixed(3) + ' m，脉压增益也会下降。');
  }
  if (Math.abs(dv.tilt) > tiltMax + 0.05)
    W.push('成像俯仰 ' + dv.tilt + '° 超过 ±' + tiltMax.toFixed(1) +
      '°（= 垂直开角 θ_v 的一半）：扇面下沿已转出发射照亮的锥体，远端亮度开始下降。' +
      '想只压近端就把俯仰收在 ±' + tiltMax.toFixed(1) + '° 以内。');
  /* 量化噪声占比：ADC 位数与前置增益不够时，噪底真的会被它顶起来 */
  if (FLS.Env && FLS.Env.noisePower && FLS.Env.adcFullScale) {
    var npd = FLS.Env.noisePower(fcHz, B, fsbb, parseFloat(P['tx.sl']) || 210);
    dv.quantFrac = npd.frac.quant;
    dv.chanFrac = npd.frac.chan;
    dv.fsDb = npd.fsDb;
    dv.nfrac = npd.frac;
    dv.noiseDb = {
      total: 10 * Math.log10(Math.max(1e-30, npd.P)),
      amb: npd.NLdb, self: npd.SELFdb, chan: npd.CHdb, quant: npd.quantDb
    };
    if (npd.frac.quant > 0.3)
      W.push('量化噪声已占接收噪底的 ' + (npd.frac.quant * 100).toFixed(0) +
        '%（' + npd.bits + ' bit、满量程折到 ' + npd.fsDb.toFixed(0) +
        ' dB）：把采样位数提到 16 bit，或把前置增益从 ' + P['rx.preGain'] +
        ' dB 加上去，噪底会明显下降。');
  }
  dv.warns = W;
  return dv;
};
/** 派生量的显示文本（参数页的只读框用） */
FLS.dvText = function (k) {
  var v = FLS.dv || {};
  if (k === 'rx.vOpen') return (v.vOpen === undefined ? '—' : v.vOpen.toFixed(1));
  if (k === 'tx.vbeam') return (v.vTx === undefined ? '—' : v.vTx.toFixed(1));
  /* ★ V3.6：接收基阵的四个派生量 */
  if (k === 'rx.aperture') return (v.Dmm === undefined ? '—' : v.Dmm.toFixed(1));
  if (k === 'rx.beam3') return (v.th3 === undefined ? '—' : (v.th3 >= 180 ? '≥180（全向）' : v.th3.toFixed(2)));
  if (k === 'rx.beam3Edge') return (v.th3Edge === undefined ? '—' : (v.th3Edge >= 180 ? '≥180（全向）' : v.th3Edge.toFixed(2)));
  /* 栅瓣：dv.thGrat ≥ 89.9° 意味着 d ≤ λ/2，全扫描范围无栅瓣 */
  if (k === 'rx.grating') {
    if (v.thGrat === undefined) return '—';
    /* 左栏宽约 290 px，派生框只有 ~80 px。这里刻意只用 3 个字：完整条件
       （d ≤ λ/2 ⇒ 全扫描范围无栅瓣）写在该行的 ? 帮助与 title 里，
       否则会被输入框截成"无（d ≤ λ/2"这种半截话。 */
    if (v.thGrat >= 89.9) return '无栅瓣';
    return (v.thGrat <= 0 ? '法向即有' : v.thGrat.toFixed(1));
  }
  if (k === 'alg.nBeam') return (v.n === undefined ? '—' : String(v.n));
  if (k === 'rx.fsbb') return (v.fsbb === undefined ? '—' : (v.fsbb / 1000).toFixed(1));
  if (k === 'rx.decim') return (v.Kdec === undefined ? '—' : String(v.Kdec));
  if (k === 'alg.rUnamb') return (v.rUn === undefined ? '—' : v.rUn.toFixed(1));
  /* ★ V3.5：摄像头矩形视场。它依赖视口宽高比（运行时 DOM 尺寸），
     所以不在 derive() 里算，而是每次显示时向 camview 现问一次。
     视口还没建（或当前不可见）时，camview 会退回默认宽高比 4:1。 */
  if (k === 'cam.fovH' || k === 'cam.fovV') {
    var CV = FLS.camview;
    if (!CV || !CV.solveFov) return '—';
    var f = CV.solveFov((CV.W && CV.H) ? (CV.W / CV.H) : 4);
    var s = (k === 'cam.fovH') ? f.h : f.v;
    return isFinite(s) ? s.toFixed(1) : '—';
  }
  return '';
};

