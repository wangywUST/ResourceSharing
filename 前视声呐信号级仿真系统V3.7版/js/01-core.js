/* ---------------------------------------------------------------- 数学工具 */
FLS.U = (function () {
  var DEG = Math.PI / 180, RAD = 180 / Math.PI;
  function clamp(v, a, b) { return v < a ? a : (v > b ? b : v); }
  function lerp(a, b, t) { return a + (b - a) * t; }
  function db2lin(db) { return Math.pow(10, db / 20); }      // 幅度域：20log10
  function lin2db(x) { return 20 * Math.log10(Math.max(1e-30, Math.abs(x))); }
  function db2pow(db) { return Math.pow(10, db / 10); }      // 功率域：10log10
  function pow2db(p) { return 10 * Math.log10(Math.max(1e-30, p)); }
  /** 可复现随机数（mulberry32） */
  function rng(seed) {
    var a = seed >>> 0;
    return function () {
      a |= 0; a = a + 0x6D2B79F5 | 0;
      var t = Math.imul(a ^ a >>> 15, 1 | a);
      t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
      return ((t ^ t >>> 14) >>> 0) / 4294967296;
    };
  }
  /** 高斯随机（Box-Muller），用传入的 rng */
  function gauss(rnd) {
    var u = 1 - rnd(), v = rnd();
    return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
  }
  /** 复数数组（交错存储 re,im）基础运算 */
  function cMake(n) { return new Float32Array(2 * n); }
  function cAdd(y, i, re, im) { y[2 * i] += re; y[2 * i + 1] += im; }
  function sinc(x) { return Math.abs(x) < 1e-12 ? 1 : Math.sin(x) / x; }
  /** 阵元/换能器指向性：等效均匀孔径 sinc 模型，由 −3dB 半功率半开角反推孔径
   *  半功率全波束宽 ≈ 0.886 λ/a → a = 0.443 λ/sin(θ_h)；
   *  D(θ) = |sinc(1.3915·θ/θ_h)|（θ、θ_h 均为弧度，θ_h 为半功率半开角） */
  function directivity(thetaRad, halfAngleRad, lam) {
    if (halfAngleRad <= 0) return 1;
    var x = 1.3915 * thetaRad / halfAngleRad;
    return Math.abs(x) < 1e-9 ? 1 : Math.abs(sinc(x));
  }
  /** 数值插值（用于 TVG 曲线等） */
  function interp1(xs, ys, x) {
    var n = xs.length; if (n === 0) return 0;
    if (x <= xs[0]) return ys[0];
    if (x >= xs[n - 1]) return ys[n - 1];
    for (var i = 1; i < n; i++) {
      if (x <= xs[i]) {
        var t = (x - xs[i - 1]) / Math.max(1e-9, xs[i] - xs[i - 1]);
        return ys[i - 1] + t * (ys[i] - ys[i - 1]);
      }
    }
    return ys[n - 1];
  }
  function parseNumList(str) {
    if (!str) return [];
    return String(str).split(/[,，;；\s]+/).map(parseFloat).filter(function (v) { return !isNaN(v); });
  }
  function fmt(v, d) {
    if (v === null || v === undefined || isNaN(v)) return '--';
    if (Math.abs(v) >= 1e5 || (Math.abs(v) < 1e-3 && v !== 0)) return v.toExponential(2);
    return v.toFixed(d === undefined ? 2 : d);
  }
  /** 高斯白噪声（复数基带，单位方差 / sqrt(2) 每分量） */
  function fillCplxNoise(arr, sigma, rnd) {
    for (var i = 0; i < arr.length; i += 2) {
      var g = gauss(rnd);
      arr[i] = g * sigma; arr[i + 1] = gauss(rnd) * sigma;
    }
  }
  return {
    DEG: DEG, RAD: RAD, clamp: clamp, lerp: lerp, db2lin: db2lin, lin2db: lin2db,
    db2pow: db2pow, pow2db: pow2db, rng: rng, gauss: gauss, cMake: cMake, cAdd: cAdd,
    sinc: sinc, directivity: directivity, interp1: interp1, parseNumList: parseNumList,
    fmt: fmt, fillCplxNoise: fillCplxNoise
  };
})();

