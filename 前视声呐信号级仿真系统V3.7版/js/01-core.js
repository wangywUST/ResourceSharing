FLS.logLines = [];
FLS.log = function (msg, level) {
  level = level || 'info';
  var w = document.getElementById('logWin');
  var d = new Date();
  var ts = ('0' + d.getHours()).slice(-2) + ':' + ('0' + d.getMinutes()).slice(-2) + ':' + ('0' + d.getSeconds()).slice(-2);
  if (w) {
    var el = document.createElement('div');
    el.className = 'l-' + level;
    el.textContent = '[' + ts + '] ' + msg;
    w.appendChild(el);
    while (w.childNodes.length > 400) w.removeChild(w.firstChild);
    w.scrollTop = w.scrollHeight;
  }
  FLS.logLines.push('[' + ts + '][' + level + '] ' + msg);
  if (FLS.logLines.length > 4000) FLS.logLines.shift();
};
