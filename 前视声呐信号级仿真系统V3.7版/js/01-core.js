/**
 * 把 state.display 绑定为 FLS.P['disp.*'] 的读写代理。
 * 读取 st.display.cone → FLS.P['disp.cone']；写入 st.display.cone = v → 同步写回 FLS.P。
 * 这样载入工程 / 切换模板替换 FLS.P 时，三维显示开关不会残留旧值。
 */
(function bindDisplayProxy() {
  var KEYS = ['axes', 'scale', 'grid', 'bbox', 'cone', 'rxCone', 'track', 'scatter', 'normal', 'heightColor'];
  var obj = {};
  KEYS.forEach(function (k) {
    Object.defineProperty(obj, k, {
      enumerable: true,
      get: function () { return !!FLS.P['disp.' + k]; },
      set: function (v) { FLS.P['disp.' + k] = !!v; }
    });
  });
  FLS.state.display = obj;
})();

