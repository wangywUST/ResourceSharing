  function A(path, text) {
    return h('a', { href: '#/' + path, text: text, style: { color: 'var(--accent)' } });
  }

  /** 带内链的富文本段落（md 会转义 HTML，故直接构造节点） */
  function raw(html) {
    return { t: 'raw', node: h('div.prose', { html: html }) };
  }
  /** 链接短句 */
  function L(path, text) {
    return '<a href="#/' + path + '">' + text + '</a>';
  }

  /** LaTeX 片段 → 纯文本（用于表格单元格：UI.table 按纯文本渲染） */
  function pt(s) {
    return String(s === undefined || s === null ? '' : s)
      .replace(/\\text\s*\{([^}]*)\}/g, '$1')
      .replace(/\\pi/g, 'π').replace(/\\pm/g, '±').replace(/\\times/g, '×')
      .replace(/\\le/g, '≤').replace(/\\ge/g, '≥').replace(/\\approx/g, '≈')
      .replace(/\\cdot/g, '·').replace(/\\lambda/g, 'λ').replace(/\\theta/g, 'θ')
      .replace(/\\mu/g, 'µ').replace(/\\omega/g, 'ω').replace(/\\Delta/g, 'Δ')
      .replace(/\\alpha/g, 'α').replace(/\\log/g, 'log').replace(/\\sin/g, 'sin')
      .replace(/\\cos/g, 'cos').replace(/\\sqrt/g, '√').replace(/\\sim/g, '～')
      .replace(/\\%/g, '%').replace(/\\,/g, ' ')
      .replace(/[{}]/g, '')
      .replace(/\\\\/g, '')
      .replace(/\\/g, '')
      .replace(/\$/g, '')
      .replace(/\*\*/g, '');
  }

  /* 本文件内临时包装 doc.register：把表格字符串单元格里的 LaTeX 转成纯文本，
     注册完成后立即还原，不影响后续加载的文件（cases/toolbox）。 */
  const _docRegister = doc.register.bind(doc);
