  /** 把一道题追加到本页笔记（notes 的 API 是覆盖式，需要先读再拼） */
  function addToNote(setKey, q) {
    const path = 'quiz/' + setKey;
    let body;
    if (q.type === 'choice') {
      body = '正确选项：' + LETTERS[q.ans] + '. ' + plain(q.opts[q.ans]) + '\n解析：' + plain(q.exp);
    } else if (q.type === 'calc') {
      body = '答案：' + q.ans + ' ' + (q.unit || '') + '\n步骤：\n' + (q.steps || []).map(plain).join('\n');
    } else {
      body = '要点：\n- ' + (q.key || []).map(plain).join('\n- ') + '\n参考：' + plain(q.exp);
    }
    const head = '## 【' + q.id + '｜' + q.diff + '｜' + TYPE_NAME[q.type] + '】' + plain(q.q).slice(0, 80);
    const old = DSP.notes.get(path) || '';
    DSP.notes.set(path, (old ? old + '\n\n' : '') + head + '\n' + body);
    DSP.notes.refreshUI();
    UI.toast('已加入笔记：' + path);
  }

